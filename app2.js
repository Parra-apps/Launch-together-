/* ---------- init: saved choice → browser language → English ---------- */
(function initLang(){
  let lang = null;
  try { lang = localStorage.getItem("twl_lang"); } catch(e){}
  if (!lang || !I18N[lang]) {
    const nav = (navigator.language || "en").toLowerCase();
    lang = nav.split("-")[0];
    if (nav.indexOf("fil") === 0) lang = "tl";
    if (!I18N[lang]) lang = "en";
  }
  applyLang(lang);
})();

/* ============================================================
   FOUNDER PANEL — visible only to the founder (member-access
   email = FOUNDER_EMAIL). Pending applications are read from
   requests.json (same folder). Approve / Reject sends the
   decision to the founder's inbox via FormSubmit; Muse
   applies decisions at the next review (updates MEMBERS and
   requests.json, then republishes). Club closes at GOAL.
   ============================================================ */
(function founderPanel(){
  function esc(s){
    return String(s == null ? "" : s).replace(/[&<>"']/g, c => ({"&":"&amp;","<":"&lt;",">":"&gt;",'"':"&quot;","'":"&#39;"}[c]));
  }
  function isFounder(){
    try {
      const e = storedEmail();
      return !!e && e.trim().toLowerCase() === FOUNDER_EMAIL;
    } catch(err){ return false; }
  }

  let pendingReqs = null; // null = not loaded yet or fetch failed

  function renderPanel(){
    const sec = document.getElementById("founderPanel");
    if (!sec) return;
    if (!isFounder()) { sec.hidden = true; return; }
    sec.hidden = false;
    const fm = document.getElementById("fpMembers");
    if (fm) fm.textContent = MEMBERS.length + " / " + GOAL;
    const fs = document.getElementById("fpSpots");
    if (fs) fs.textContent = Math.max(0, GOAL - MEMBERS.length);
    const ml = document.getElementById("fpMembersList");
    if (ml) {
      ml.innerHTML = MEMBERS.map(m => {
        const bits = [];
        (m.testing || []).forEach(a => bits.push(esc(a.name) + " · " + t("day_of") + " " + dayOf14(a.start) + " / 14"));
        (m.launched || []).forEach(a => bits.push(esc(a.name) + " ✓"));
        return '<div class="fp-member"><strong>' + esc(m.name) + '</strong>' +
          (bits.length ? '<span>' + bits.join(" · ") + '</span>' : '') + '</div>';
      }).join("");
    }
    const box = document.getElementById("fpRequests");
    if (box) {
      if (!pendingReqs || !pendingReqs.length) {
        box.innerHTML = '<p class="empty-note">' + t("req_none") + '</p>';
      } else {
        box.innerHTML = "";
        pendingReqs.forEach(r => box.appendChild(reqCard(r)));
      }
    }
  }

  function reqCard(r){
    const card = document.createElement("div");
    card.className = "fp-req";
    const meta = [r.appName, r.country, r.telegram, r.received].filter(Boolean).map(esc).join(" · ");
    card.innerHTML =
      '<div class="fp-req-main"><div class="fp-req-name">' + esc(r.name || "") + '</div>' +
      (meta ? '<div class="fp-req-meta">' + meta + '</div>' : '') +
      '<div class="fp-req-meta">' + esc(r.email || "") + '</div></div>' +
      '<div class="fp-req-actions">' +
      '<button type="button" class="btn teal small" data-decision="approve">✅ ' + t("btn_approve") + '</button>' +
      '<button type="button" class="btn small" data-decision="reject">❌ ' + t("btn_reject") + '</button>' +
      '</div>' +
      '<p class="fp-sent" hidden>' + t("decision_sent") + '</p>';
    card.querySelectorAll("button[data-decision]").forEach(btn => {
      btn.addEventListener("click", () => sendDecision(r, btn.getAttribute("data-decision"), card));
    });
    return card;
  }

  function sendDecision(r, decision, card){
    const body = new URLSearchParams();
    body.set("_subject", "TWL DECISION: " + (decision === "approve" ? "APPROVE" : "REJECT") + " " + (r.email || ""));
    body.set("decision", decision);
    body.set("applicant_name", r.name || "");
    body.set("applicant_email", r.email || "");
    body.set("_captcha", "false");
    body.set("_template", "table");
    try {
      fetch("https://formsubmit.co/cuidajuntos.app@gmail.com", {
        method: "POST", mode: "no-cors",
        headers: { "Content-Type": "application/x-www-form-urlencoded" },
        body: body.toString()
      }).catch(() => {});
    } catch(err){}
    card.querySelectorAll("button[data-decision]").forEach(b => { b.disabled = true; });
    const sent = card.querySelector(".fp-sent");
    if (sent) sent.hidden = false;
  }

  /* ---- club full: close the join form at GOAL members ---- */
  function applyClubFull(){
    if (MEMBERS.length < GOAL) return;
    const joinCard = document.querySelector("#join .join-card");
    if (joinCard) {
      const note = joinCard.querySelector(".club-full-note");
      if (note) note.textContent = t("club_full");
      else joinCard.innerHTML = '<div class="club-full-note">' + t("club_full") + '</div>';
    }
    document.querySelectorAll('a.btn[href="#join"]').forEach(a => { a.style.display = "none"; });
  }

  /* ---- load pending applications (never breaks the page) ---- */
  function loadRequests(){
    try {
      fetch("requests.json?t=" + Date.now(), { cache: "no-store" })
        .then(res => (res && res.ok) ? res.json() : null)
        .then(data => {
          pendingReqs = (data && Array.isArray(data.pending)) ? data.pending : [];
          renderPanel();
        })
        .catch(() => { pendingReqs = []; renderPanel(); });
    } catch(err){ pendingReqs = []; renderPanel(); }
  }

  /* ---- re-render on language change and on access login/logout ---- */
  const origApplyLang = applyLang;
  applyLang = function(lang){ origApplyLang(lang); renderPanel(); applyClubFull(); };
  const origRefreshAccess = refreshAccessUI;
  refreshAccessUI = function(){ origRefreshAccess(); renderPanel(); };

  renderPanel();
  applyClubFull();
  loadRequests();
})();
